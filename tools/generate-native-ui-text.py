#!/usr/bin/env python3
"""Compile the deliberate English native UI catalogue; no dependencies or IO beyond files.

This covers selected interface captions only. Author text, serialized IDs,
format strings, worker errors and specialised tool captions are not rewritten.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'apps/native-writer/locales/en.json'
TARGET = ROOT / 'apps/native-writer/src/ui_text_catalog.rs'


def object_pairs(pairs):
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise ValueError('Duplicate catalogue key: ' + key)
        obj[key] = value
    return obj


def load(raw):
    value = json.loads(raw, object_pairs_hook=object_pairs)
    if not isinstance(value, dict) or set(value) != {'schemaVersion', 'locale', 'strings'}:
        raise ValueError('Unsupported UI catalogue shape')
    if type(value['schemaVersion']) is not int or value['schemaVersion'] != 1 or value['locale'] != 'en':
        raise ValueError('Only the explicit schema-1 English catalogue is supported')
    strings = value['strings']
    if not isinstance(strings, dict) or not 1 <= len(strings) <= 2000:
        raise ValueError('Invalid bounded UI string collection')
    for key, text in strings.items():
        if not isinstance(key, str) or not re.fullmatch(r'[a-z][a-z0-9]*(?:[._][a-z0-9]+)*', key) or len(key) > 128:
            raise ValueError('Invalid stable UI key')
        if not isinstance(text, str) or not 1 <= len(text) <= 4000 or any((ord(c) < 32 and not (c == "\n" and key.startswith(("cli.", "body.")))) or 127 <= ord(c) <= 159 or 0xD800 <= ord(c) <= 0xDFFF for c in text):
            raise ValueError('Invalid bounded UI caption: ' + key)
        if '{' in text or '}' in text:
            raise ValueError('Formatted captions need a separate explicit argument contract: ' + key)
    return strings


def render(strings):
    lines = ['// Generated by tools/generate-native-ui-text.py; edit locales/en.json.',
             '// Interface captions only; author content and serialized identifiers are separate.',
             'const ENGLISH: &[(&str, &str)] = &[']
    for key, value in sorted(strings.items()):
        # JSON escaping of these validated printable strings is Rust-compatible;
        # literal Unicode is retained rather than emitted as JSON-only escapes.
        lines.append('    (' + json.dumps(key, ensure_ascii=False) + ', ' + json.dumps(value, ensure_ascii=False) + '),')
    lines += ['];', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        output = render(load(SOURCE.read_text(encoding='utf-8')))
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + '\n')
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding='utf-8') != output:
            parser.exit(1, 'Native UI catalogue is stale; run tools/generate-native-ui-text.py.\n')
        print('Native English catalogue is current.')
    else:
        TARGET.write_text(output, encoding='utf-8')


if __name__ == '__main__':
    main()
